-- 단말 토큰 세대 번호.
--
-- 정본 물리 모델(2026-07-23-데이터모델링)에는 단말 인증 수단이 없다. mdm.terminal은
-- 코드·공장·위치·유형·상태만 갖는다 — REQ-PR-0023(현장 로그인 생략)이 인증을 '사번 입력'
-- 으로만 규정하고, 그 사번을 무엇이 신뢰하는지는 설계에서 빠진 결과다.
-- 설계 근거: research/2026-07-28-POP-단말인증-설계검토.md §3.2
--
-- ⚠ 이 컬럼은 OMF-MES 구현 측 추가분이다. 모델링 정본 SQL에 역반영이 필요하다.
--
-- 왜 필요한가:
--   토큰 폐기가 성립하지 않았다. is_active는 스위치일 뿐이라 단말을 다시 켜면 유출된
--   토큰도 함께 되살아난다(실측: 비활성화 401 → 재활성화 200). 토큰이 1년짜리라
--   그 상태가 오래 간다. 유출분을 영구히 끊는 유일한 방법이 terminal_code를 버리고
--   새로 만드는 것이었고, 그러면 폐기 코드가 마스터에 계속 쌓인다.
--
-- 어떻게 쓰는가:
--   발급 시 +1 하고 그 값을 토큰 클레임 tv에 담는다. 매 요청 대조해 다르면 거부한다.
--   재발급이 곧 이전 토큰 전부의 무효화가 된다. terminal 행은 이미 매 요청 읽으므로
--   추가 조회가 없다.
--
-- 별도 테이블(app.terminal_credential)을 두지 않은 이유:
--   발급 이력을 남기지 않기로 해서(단말이 무엇을 했는지는 트랜잭션의 terminal_id로 이미
--   추적된다) 의미 있는 컬럼이 이것 하나뿐이다. 한 컬럼을 위해 테이블을 만들면 JOIN
--   비용만 늘어난다. 이력 요구가 생기면 그때 분리한다.

ALTER TABLE mdm.terminal
    ADD COLUMN token_version integer NOT NULL DEFAULT 1 CHECK (token_version > 0);

COMMENT ON COLUMN mdm.terminal.token_version IS
    '단말 토큰 세대. 발급 시 증가하며 이전 세대 토큰은 즉시 무효가 된다. 정본 모델 미포함 — OMF-MES 구현 측 추가분(2026-07-28).';
