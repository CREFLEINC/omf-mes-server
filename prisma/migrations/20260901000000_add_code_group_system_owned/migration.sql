-- 공통코드 그룹의 「시스템 소유」 플래그.
--
-- 요청: 이슈 #62 「그룹 속성 신설 1건」 · 설계 회신 2026-09-01
-- 계약: 공유계약 G-31(마스터안전형 판정 기준) · G-32(공통코드 그룹 등록부)
--
-- 무엇을 가르는가:
--   공통코드 그룹은 두 부류다. 값이 분류·필터로만 쓰여 고객이 운영 중에 바꿔도 되는 것
--   (G-31 「마스터안전형」)과, 값에 서버 동작·화면 분기가 걸려 있어 바뀌면 깨지는 것이다.
--   지금까지 그 구분을 담을 자리가 없어 W-06-06(공통코드 마스터)이 모든 그룹에 값 추가·
--   삭제 버튼을 똑같이 열어 두었다.
--
-- 왜 값 단위가 아니라 그룹 단위인가:
--   설계 요청이 그룹 전체를 잠그는 형태다. 값 하나만 잠그면 「그 값은 못 지우지만 새 값은
--   더할 수 있다」가 되는데, 상태 기계가 깨지는 것은 대개 «모르는 값이 들어올 때»라
--   추가를 막지 못하면 잠근 의미가 없다.
--
-- 왜 DEFAULT false 인가:
--   참으로 두면 모든 그룹이 잠겨 W-06-06 이 통째로 읽기 전용이 된다 — 고객이 정당하게
--   편집해야 할 G-31 그룹까지 막힌다. 거짓으로 두고 잠글 그룹만 시드에서 참으로 올린다.
--
--   ⚠ 방향의 위험이 비대칭이라는 것은 알아 둔다. 과잉 잠금은 불편에 그치지만, 잠갔어야
--   할 그룹을 놓치면 고객이 값을 더해 상태 기계가 깨진다. 이 컬럼에는 참조 무결성이
--   없으므로(mdm.code_value 를 가리키는 FK 가 물리 전체에 0건이다) DB 가 잡아 주지
--   않는다. 잠글 그룹 목록은 시드가 정본이며, 새 그룹을 세울 때 함께 판정한다.
--
-- 첫 대상 세 그룹(시드에서 참으로 올린다 — 이 마이그레이션에서는 올리지 않는다):
--   WORK_SESSION_EVENT_TYPE  값에 따라 세션 상태·사유 필수 여부·사유 목록이 갈린다(#62)
--   WORK_ORDER_STATUS        작업지시 상태 기계. 설계 회신이 「G-31 이 아니다」로 못박았다
--   JUDGMENT_TYPE            통제 속성이 출고·출하·피킹을 막는다(#63 E-1 · 설계 회신)
--
--   값을 넣지 않는 이유는 이 마이그레이션이 적용되는 시점에 그 그룹 행이 있다는 보장이
--   없어서다. 시드가 그룹을 upsert 하면서 함께 세운다.

ALTER TABLE mdm.code_group
    ADD COLUMN is_system_owned boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN mdm.code_group.is_system_owned IS
    '시스템 소유 그룹 여부. 참이면 값에 서버 동작·화면 분기가 걸려 있어 고객이 값을 추가·삭제할 수 없다 — W-06-06 이 이 플래그를 보고 버튼을 잠근다. 거짓이면 G-31 마스터안전형(분류·필터용)이다. 근거: 공유계약 G-31 · 이슈 #62.';
