-- 추적 시스템(flowtrack)에서 받아 처리한 전송 하나가 한 행이다. 거절한 전송은 남기지 않는다.
-- flowtrack 은 실패한 전송을 언제든 다시 보내므로 전송 번호를 기한 없이 기억한다 — Idempotency-Key 의 72시간으로는 모자란다.
CREATE TABLE integration.tracking_transmission (
  tracking_transmission_id bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transmission_id          uuid        NOT NULL,
  kind_code                varchar(50) NOT NULL,
  plant_id                 bigint      NOT NULL REFERENCES mdm.plant(plant_id),
  -- 출하 출고처럼 W/O 가 없는 전송이 있다.
  work_order_id            bigint      REFERENCES production.work_order(work_order_id),
  payload                  jsonb       NOT NULL,
  received_at              timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT uq_tracking_transmission UNIQUE (transmission_id)
);

-- 그 전송이 만든 문서. document_type_code 는 문서 표 이름이다(A-10).
CREATE TABLE integration.tracking_transmission_document (
  tracking_transmission_id bigint      NOT NULL REFERENCES integration.tracking_transmission(tracking_transmission_id),
  document_type_code       varchar(50) NOT NULL,
  document_id              bigint      NOT NULL,
  PRIMARY KEY (tracking_transmission_id, document_type_code, document_id)
);
