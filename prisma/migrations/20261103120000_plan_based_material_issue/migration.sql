-- 계획 기반 출고 요청(피처 003 · omf-all-around#66). 생산 창고 → 생산 현장 요청서를 W/O 배포 때 「대기」로 만들고
-- 출고 작업일 00:00 에 배포한다. 칸·표를 더하기만 한다 — 기존 행은 새 칸이 NULL 이고 옛 동작 그대로다.

-- 출고 요청 머리 — 출발 창고·출고 작업일·배포/닫힘/취소 기록.
ALTER TABLE logistics.material_issue_request
    ADD COLUMN source_warehouse_id  bigint REFERENCES mdm.warehouse(warehouse_id),
    ADD COLUMN issue_work_date      date,
    ADD COLUMN released_at          timestamptz,
    ADD COLUMN release_attempted_at timestamptz,
    ADD COLUMN release_error_text   varchar(1000),
    ADD COLUMN closed_at            timestamptz,
    ADD COLUMN close_reason_code    varchar(50),
    ADD COLUMN cancelled_at         timestamptz,
    ADD COLUMN cancelled_by         bigint;

COMMENT ON COLUMN logistics.material_issue_request.source_warehouse_id IS
    '출발 생산 창고. 새 요청은 필수(서비스 검증). NULL = 이 기능 전 요청 또는 생산 창고 없는 공장 — 출고 예정 재고에서 뺀다.';
COMMENT ON COLUMN logistics.material_issue_request.issue_work_date IS
    '출고 작업일(공장 현지 날짜). 생산일의 직전 근무일. 이날 공장 현지 00:00 에 대기 요청을 배포한다.';
COMMENT ON COLUMN logistics.material_issue_request.released_at IS 'WAITING → REGISTERED 시각. 즉시 배포도 기록.';
COMMENT ON COLUMN logistics.material_issue_request.release_attempted_at IS '마지막 배포 시도 시각.';
COMMENT ON COLUMN logistics.material_issue_request.release_error_text IS '마지막 배포 실패 원인. 성공하면 NULL.';
COMMENT ON COLUMN logistics.material_issue_request.closed_at IS
    '진행된 요청의 미출고분을 닫은 시각(W/O 취소·마감). 상태는 그대로 두고 출고 예정에서 뺀다.';
COMMENT ON COLUMN logistics.material_issue_request.close_reason_code IS 'WO_CANCELLED | WO_CLOSED';
COMMENT ON COLUMN logistics.material_issue_request.cancelled_at IS '요청 취소 시각.';
COMMENT ON COLUMN logistics.material_issue_request.cancelled_by IS '요청을 취소한 사용자.';

-- 00:00 러너가 「대기이고 출고 작업일이 오늘 이하」를 고른다.
CREATE INDEX ix_material_issue_request_status_work_date
    ON logistics.material_issue_request (status_code, issue_work_date);
-- 출고 예정 재고는 (출발 창고, 활성 상태) 요청 줄의 합이다.
CREATE INDEX ix_material_issue_request_source_status
    ON logistics.material_issue_request (source_warehouse_id, status_code);

ALTER TABLE logistics.material_issue_request_line
    ADD COLUMN shortage_qty decimal(20, 6) NOT NULL DEFAULT 0;

COMMENT ON COLUMN logistics.material_issue_request_line.shortage_qty IS
    '만들 때 쓸 수 있는 양(가용 − 출고 예정)에 걸려 줄인 양. 소요 = requested_qty + shortage_qty.';

-- 부서 생산 창고. 부서에는 공장 축이 없어 다른 공장 창고가 섞일 수 있다 — 출발 창고는 W/O 공장 창고만 후보로 본다.
CREATE TABLE mdm.department_production_warehouse (
    department_id bigint      NOT NULL REFERENCES mdm.department(department_id),
    warehouse_id  bigint      NOT NULL REFERENCES mdm.warehouse(warehouse_id),
    created_at    timestamptz NOT NULL DEFAULT clock_timestamp(),
    created_by    bigint,
    CONSTRAINT pk_department_production_warehouse PRIMARY KEY (department_id, warehouse_id)
);

CREATE INDEX ix_department_production_warehouse_warehouse
    ON mdm.department_production_warehouse (warehouse_id);

COMMENT ON TABLE mdm.department_production_warehouse IS
    '부서 생산 창고. 한 행이라도 있는 공장은 출고 요청을 생산 창고에서 내는 「새 규칙」, 없으면 지금 방식(FR-009a).';

-- 어느 부서 생산 창고에도 가용 재고가 없어 요청에 넣지 못한 자재(W/O × 자재). 소요는 저장되지 않으므로 배포 때 남긴다.
CREATE TABLE logistics.material_issue_unsourced_shortage (
    material_issue_unsourced_shortage_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_id       bigint         NOT NULL REFERENCES production.work_order(work_order_id),
    item_id             bigint         NOT NULL REFERENCES mdm.item(item_id),
    uom_id              bigint         NOT NULL REFERENCES mdm.uom(uom_id),
    shortage_qty        decimal(20, 6) NOT NULL,
    resolved_request_id bigint REFERENCES logistics.material_issue_request(material_issue_request_id),
    created_at          timestamptz    NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_material_issue_unsourced_shortage UNIQUE (work_order_id, item_id),
    CONSTRAINT ck_material_issue_unsourced_shortage_qty CHECK (shortage_qty > 0)
);

COMMENT ON TABLE logistics.material_issue_unsourced_shortage IS
    '재고 있는 생산 창고가 없어 출고 요청에 넣지 못한 자재. 지우지 않는다 — 조회는 W/O 가 취소·마감이 아닌 행만.';
COMMENT ON COLUMN logistics.material_issue_unsourced_shortage.shortage_qty IS '배포 때 그 자재의 소요 수량 전부.';
COMMENT ON COLUMN logistics.material_issue_unsourced_shortage.resolved_request_id IS
    '이 행에서 만든 보충 요청(W-02-10). 재고가 생겨도 요청서를 자동으로 만들지 않는다.';

