-- 이벤트 알림 — 알림센터·Zalo (omf-all-around#160 · specs/001-zalo-production-alerts data-model §1·§2).
-- forward-only: 칸·표 추가만 한다. 기존 notification_subscription* 표는 건드리지 않는다(보존·미사용, research R-10).

-- §1 기존 표에 칸 추가 ----------------------------------------------------------

-- 표준형 84 + 9자리(베트남 휴대폰). 공용 단말 계정이 같은 번호를 쓸 수 있어 UNIQUE 는 두지 않는다.
ALTER TABLE app.app_user
  ADD COLUMN phone_number varchar(20),
  ADD CONSTRAINT ck_app_user_phone_number CHECK (phone_number ~ '^84[35789][0-9]{8}$');

-- 라인·설비 그룹 노드 «자신»의 담당 부서. 상위 라인으로 상속하지 않는다(research R-7).
ALTER TABLE mdm.production_line
  ADD COLUMN department_id bigint REFERENCES mdm.department(department_id);
CREATE INDEX ix_production_line_department ON mdm.production_line (department_id);

-- notification_event 는 아직 0행이라 DEFAULT 붙인 NOT NULL 추가가 안전하다.
ALTER TABLE app.notification_event
  ADD COLUMN department_id bigint REFERENCES mdm.department(department_id),
  ADD COLUMN dispatch_status_code varchar(30) NOT NULL DEFAULT 'NOTIFIED',
  ADD COLUMN skip_reason_code varchar(40),
  ADD CONSTRAINT ck_notification_event_dispatch_status
    CHECK (dispatch_status_code IN ('NOTIFIED', 'SKIPPED')),
  ADD CONSTRAINT ck_notification_event_skip_reason
    CHECK ((dispatch_status_code = 'SKIPPED') = (skip_reason_code IS NOT NULL));

COMMENT ON COLUMN app.app_user.phone_number IS
  '베트남 휴대폰 표준형 84XXXXXXXXX(Zalo phone 형식). 서버 readPhone() 이 정규화·검증한다. Zalo 발송용.';
COMMENT ON COLUMN mdm.production_line.department_id IS
  '라인·설비 그룹의 담당 부서. 알림 부서 판정 기준. 상위 라인 부서를 상속하지 않는다.';
COMMENT ON COLUMN app.notification_event.department_id IS '판정된 부서. 판정 실패면 NULL.';
COMMENT ON COLUMN app.notification_event.dispatch_status_code IS 'NOTIFIED | SKIPPED';
COMMENT ON COLUMN app.notification_event.skip_reason_code IS
  'SKIPPED 일 때만: DEPARTMENT_UNRESOLVED | EVENT_DISABLED | NO_RECIPIENTS | REPORTER_OPTED_OUT | APPROVER_INACTIVE';

-- §2 부서×이벤트 설정 ----------------------------------------------------------

CREATE TABLE app.notification_department_setting (
  notification_department_setting_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_id   bigint      NOT NULL REFERENCES mdm.department(department_id),
  event_type_code varchar(60) NOT NULL,
  is_enabled      boolean     NOT NULL DEFAULT false,
  zalo_enabled    boolean     NOT NULL DEFAULT false,
  version_no      integer     NOT NULL DEFAULT 1 CHECK (version_no > 0),
  created_at      timestamptz NOT NULL DEFAULT clock_timestamp(),
  created_by      bigint,
  updated_at      timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_by      bigint,
  CONSTRAINT uq_notification_department_setting UNIQUE (department_id, event_type_code)
);

CREATE TABLE app.notification_department_recipient (
  notification_department_recipient_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notification_department_setting_id bigint NOT NULL
    -- 이름을 적는 이유: PostgreSQL 기본 이름(63자 절단)과 Prisma 기대 이름이 달라 drift 가 난다.
    CONSTRAINT notification_department_recipient_notification_department__fkey
    REFERENCES app.notification_department_setting(notification_department_setting_id),
  app_user_id bigint      NOT NULL REFERENCES app.app_user(app_user_id),
  created_at  timestamptz NOT NULL DEFAULT clock_timestamp(),
  created_by  bigint,
  CONSTRAINT uq_notification_department_recipient UNIQUE (notification_department_setting_id, app_user_id)
);
CREATE INDEX ix_notification_department_recipient_user ON app.notification_department_recipient (app_user_id);

COMMENT ON TABLE app.notification_department_setting IS
  '부서×이벤트 알림 설정. 행이 없으면 끔·Zalo 끔·수신자 0명·version 1 로 읽는다(GET 은 행을 만들지 않는다).';
COMMENT ON COLUMN app.notification_department_setting.event_type_code IS '이벤트 카탈로그 6종 중 하나(서버 검증).';
COMMENT ON COLUMN app.notification_department_setting.zalo_enabled IS
  'Zalo 부가 전달. is_enabled=true 일 때만 효과가 있고, 꺼져 있어도 값은 저장한다.';
COMMENT ON TABLE app.notification_department_recipient IS
  '부서×이벤트 설정의 개인 수신자. APPROVAL_ACTION_REQUIRED(결재자 모드) 설정에는 두지 않는다.';

-- §2 Zalo 연결·템플릿·발송 ------------------------------------------------------

CREATE TABLE app.zalo_connection (
  zalo_connection_id      smallint     PRIMARY KEY CHECK (zalo_connection_id = 1),
  app_id                  varchar(40),
  secret_key_enc          text,
  refresh_token_enc       text,
  access_token_enc        text,
  access_token_expires_at timestamptz,
  status_code             varchar(30)  NOT NULL DEFAULT 'NOT_CONFIGURED'
    CHECK (status_code IN ('NOT_CONFIGURED', 'ACTIVE', 'REAUTH_REQUIRED')),
  last_error_code         varchar(20),
  last_error_message      varchar(500),
  last_refreshed_at       timestamptz,
  param_max_length        integer      NOT NULL DEFAULT 100 CHECK (param_max_length BETWEEN 20 AND 400),
  version_no              integer      NOT NULL DEFAULT 1 CHECK (version_no > 0),
  updated_at              timestamptz  NOT NULL DEFAULT clock_timestamp(),
  updated_by              bigint
);

COMMENT ON TABLE app.zalo_connection IS 'Zalo ZBS 연결 정보. 시스템에 1행(id=1).';
COMMENT ON COLUMN app.zalo_connection.secret_key_enc IS 'AES-256-GCM 암호문(v1:iv:tag:ct). 키는 env ZALO_CREDENTIAL_KEY. 원문 저장 금지.';
COMMENT ON COLUMN app.zalo_connection.refresh_token_enc IS 'AES-256-GCM 암호문. 갱신할 때마다 회전한다.';
COMMENT ON COLUMN app.zalo_connection.access_token_enc IS 'AES-256-GCM 암호문.';
COMMENT ON COLUMN app.zalo_connection.status_code IS 'NOT_CONFIGURED | ACTIVE | REAUTH_REQUIRED';
COMMENT ON COLUMN app.zalo_connection.last_error_message IS '토큰이 섞이지 않은 문구만 남긴다.';
COMMENT ON COLUMN app.zalo_connection.param_max_length IS 'Zalo 템플릿 값 자르기 길이.';

CREATE TABLE app.zalo_template (
  event_type_code varchar(60) PRIMARY KEY,
  template_id     varchar(40) NOT NULL,
  updated_at      timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_by      bigint
);

COMMENT ON TABLE app.zalo_template IS
  '이벤트별 Zalo 템플릿 ID. 행이 없는 이벤트의 Zalo 발송은 FAILED(TEMPLATE_NOT_SET)로 남는다.';

CREATE TABLE app.zalo_delivery (
  zalo_delivery_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notification_event_id bigint       NOT NULL REFERENCES app.notification_event(notification_event_id),
  recipient_user_id     bigint       NOT NULL REFERENCES app.app_user(app_user_id),
  phone_number          varchar(20)  NOT NULL,
  event_type_code       varchar(60)  NOT NULL,
  department_id         bigint,
  template_data         jsonb        NOT NULL,
  tracking_id           varchar(48)  NOT NULL,
  status_code           varchar(20)  NOT NULL DEFAULT 'PENDING'
    CHECK (status_code IN ('PENDING', 'SENDING', 'SENT', 'FAILED', 'EXPIRED')),
  attempt_count         integer      NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
  next_attempt_at       timestamptz  NOT NULL DEFAULT now(),
  expires_at            timestamptz  NOT NULL,
  last_error_code       varchar(20),
  last_error_message    varchar(500),
  zalo_msg_id           varchar(60),
  sent_at               timestamptz,
  created_at            timestamptz  NOT NULL DEFAULT clock_timestamp(),
  updated_at            timestamptz  NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT uq_zalo_delivery_tracking UNIQUE (tracking_id),
  CONSTRAINT uq_zalo_delivery_recipient UNIQUE (notification_event_id, recipient_user_id)
);
CREATE INDEX ix_zalo_delivery_due ON app.zalo_delivery (status_code, next_attempt_at);
CREATE INDEX ix_zalo_delivery_created ON app.zalo_delivery (created_at);

COMMENT ON TABLE app.zalo_delivery IS 'Zalo 발송 1건(이벤트 × 수신자). 알림센터(app.notification)가 정본이고 이 표는 부가 경로다.';
COMMENT ON COLUMN app.zalo_delivery.phone_number IS '발생 시점 번호 스냅샷.';
COMMENT ON COLUMN app.zalo_delivery.event_type_code IS '조회용 비정규화.';
COMMENT ON COLUMN app.zalo_delivery.department_id IS '조회용 비정규화.';
COMMENT ON COLUMN app.zalo_delivery.template_data IS '자르기 적용 후 Zalo template_data.';
COMMENT ON COLUMN app.zalo_delivery.tracking_id IS 'zd-{zalo_delivery_id}. Zalo 측 기록과 대조하는 키.';
COMMENT ON COLUMN app.zalo_delivery.attempt_count IS '실제로 Zalo 에 요청을 보낸 횟수. 최대 4(최초 1 + 재시도 3).';
COMMENT ON COLUMN app.zalo_delivery.expires_at IS 'occurred_at + 24h. 지나면 EXPIRED.';
COMMENT ON COLUMN app.zalo_delivery.last_error_code IS
  'Zalo error 또는 내부 코드(NETWORK, HTTP_5xx, TEMPLATE_NOT_SET, CONNECTION_NOT_READY, UNKNOWN_OUTCOME).';
