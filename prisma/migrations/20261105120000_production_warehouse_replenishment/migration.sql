-- 생산 창고 보충(피처 004 · omf-all-around#230). 생산 창고가 자재 창고에 W/O 없이 자재를 요청한다(직접·자동).
-- 칸·표를 더하고 NOT NULL 을 푸는 것뿐이다 — 기존 행은 request_type_code 기본값 WORK_ORDER 로 옛 동작 그대로다.
-- ⚠ 보충 행을 만드는 코드는 W/O null 을 견디는 읽기 코드가 배포된 뒤에 나간다(research R-13).

-- 자동 보충 실행 기록 — 출고 요청이 FK 로 가리키므로 먼저 만든다.
CREATE TABLE logistics.replenishment_run (
    replenishment_run_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id          bigint        NOT NULL REFERENCES mdm.warehouse(warehouse_id),
    run_date              date          NOT NULL,
    started_at            timestamptz   NOT NULL DEFAULT clock_timestamp(),
    finished_at           timestamptz,
    status_code           varchar(20)   NOT NULL,
    checked_item_count    int           NOT NULL DEFAULT 0,
    created_request_count int           NOT NULL DEFAULT 0,
    error_text            varchar(1000),
    CONSTRAINT uq_replenishment_run_warehouse_date UNIQUE (warehouse_id, run_date),
    CONSTRAINT ck_replenishment_run_status CHECK (status_code IN ('DONE', 'FAILED'))
);

COMMENT ON TABLE logistics.replenishment_run IS '생산 창고별 하루 한 번 자동 보충 실행 기록. 같은 날 두 번 돌지 않게 (창고, 날짜) 유일.';
COMMENT ON COLUMN logistics.replenishment_run.run_date IS '공장 현지 날짜(plant.timezone_code 로 푼 값).';
COMMENT ON COLUMN logistics.replenishment_run.status_code IS 'DONE | FAILED';
COMMENT ON COLUMN logistics.replenishment_run.checked_item_count IS '살펴본 관리 품목 수. 보충 시점 이상이라 행을 남기지 않은 품목도 센다.';
COMMENT ON COLUMN logistics.replenishment_run.created_request_count IS '이 실행이 만든 창고 보충 요청 수.';

-- 출고 요청 머리 — 유형 칸을 더해 W/O 없는 창고 보충 요청을 같은 표에 담는다(research R-1).
ALTER TABLE logistics.material_issue_request
    ALTER COLUMN work_order_id DROP NOT NULL,
    ADD COLUMN request_type_code         varchar(30) NOT NULL DEFAULT 'WORK_ORDER',
    ADD COLUMN replenishment_origin_code varchar(10),
    ADD COLUMN replenishment_run_id      bigint REFERENCES logistics.replenishment_run(replenishment_run_id),
    ADD COLUMN close_remark              varchar(500),
    ADD COLUMN closed_by                 bigint,
    ADD COLUMN close_reason_detail_code  varchar(50),
    ADD CONSTRAINT ck_mir_type_wo CHECK (
        (request_type_code = 'WORK_ORDER' AND work_order_id IS NOT NULL)
        OR (request_type_code = 'REPLENISHMENT' AND work_order_id IS NULL
            AND source_warehouse_id IS NOT NULL AND replenishment_origin_code IS NOT NULL)
    );

COMMENT ON COLUMN logistics.material_issue_request.work_order_id IS 'W/O 요청이면 필수, 창고 보충 요청이면 NULL(ck_mir_type_wo).';
COMMENT ON COLUMN logistics.material_issue_request.request_type_code IS
    'WORK_ORDER | REPLENISHMENT. 시스템 소유 값(공통코드 아님).';
COMMENT ON COLUMN logistics.material_issue_request.replenishment_origin_code IS '창고 보충 요청만: DIRECT(직접) | AUTO(자동).';
COMMENT ON COLUMN logistics.material_issue_request.replenishment_run_id IS '자동 보충이 만든 요청이면 그 실행.';
COMMENT ON COLUMN logistics.material_issue_request.close_remark IS '잔량 마감 메모.';
COMMENT ON COLUMN logistics.material_issue_request.closed_by IS '잔량 마감한 사용자. W/O 취소·마감으로 닫힌 요청은 NULL.';
COMMENT ON COLUMN logistics.material_issue_request.close_reason_detail_code IS
    '잔량 마감 사유(REPLENISHMENT_CLOSE_REASON 코드값). close_reason_code = REMAINDER_CLOSED 일 때만.';
COMMENT ON COLUMN logistics.material_issue_request.close_reason_code IS 'WO_CANCELLED | WO_CLOSED | REMAINDER_CLOSED';

CREATE INDEX ix_material_issue_request_type_status
    ON logistics.material_issue_request (request_type_code, status_code);
-- 같은 생산 창고·품목에 진행 중 보충이 있는지(자동 보충은 건너뛴다) 판정용.
CREATE INDEX ix_material_issue_request_replenishment_active
    ON logistics.material_issue_request (destination_location_id)
    WHERE request_type_code = 'REPLENISHMENT' AND closed_at IS NULL AND status_code IN ('WAITING', 'REGISTERED');

-- 생산창고 입고 기록 — 보충 출고 수령은 W/O 가 없다.
ALTER TABLE logistics.shopfloor_receipt ALTER COLUMN work_order_id DROP NOT NULL;
COMMENT ON COLUMN logistics.shopfloor_receipt.work_order_id IS 'W/O 출고 수령이면 그 W/O, 창고 보충 출고 수령이면 NULL.';

-- 적치 지시 — 구매 입고 줄 또는 보충 수령 줄에서 생긴다.
ALTER TABLE logistics.putaway_task
    ALTER COLUMN goods_receipt_line_id DROP NOT NULL,
    ADD COLUMN shopfloor_receipt_line_id bigint REFERENCES logistics.shopfloor_receipt_line(shopfloor_receipt_line_id),
    ADD CONSTRAINT ck_putaway_task_origin CHECK (num_nonnulls(goods_receipt_line_id, shopfloor_receipt_line_id) = 1);

COMMENT ON COLUMN logistics.putaway_task.shopfloor_receipt_line_id IS '창고 보충 수령 줄에서 생긴 적치 지시. goods_receipt_line_id 와 정확히 하나만 있다.';
CREATE INDEX ix_putaway_task_shopfloor_receipt_line ON logistics.putaway_task (shopfloor_receipt_line_id);

-- 관리 품목(유지 기준). 단위는 품목 기본 단위라 칸이 없다.
CREATE TABLE logistics.replenishment_item (
    replenishment_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id          bigint         NOT NULL REFERENCES mdm.warehouse(warehouse_id),
    item_id               bigint         NOT NULL REFERENCES mdm.item(item_id),
    reorder_point_qty     decimal(20, 6) NOT NULL,
    target_qty            decimal(20, 6) NOT NULL,
    source_warehouse_id   bigint         NOT NULL REFERENCES mdm.warehouse(warehouse_id),
    created_at            timestamptz    NOT NULL DEFAULT clock_timestamp(),
    created_by            bigint,
    updated_at            timestamptz    NOT NULL DEFAULT clock_timestamp(),
    updated_by            bigint,
    version_no            int            NOT NULL DEFAULT 1,
    CONSTRAINT uq_replenishment_item UNIQUE (warehouse_id, item_id),
    CONSTRAINT ck_replenishment_item_point CHECK (reorder_point_qty > 0),
    CONSTRAINT ck_replenishment_item_target CHECK (target_qty > reorder_point_qty),
    CONSTRAINT ck_replenishment_item_source CHECK (source_warehouse_id <> warehouse_id),
    CONSTRAINT ck_replenishment_item_version CHECK (version_no > 0)
);

COMMENT ON TABLE logistics.replenishment_item IS '생산 창고 관리 품목. 쓸 수 있는 양이 보충 시점 미만이면 유지량까지 자재 창고에 요청한다.';
COMMENT ON COLUMN logistics.replenishment_item.warehouse_id IS '생산 창고(부서 생산 창고로 연결된 창고).';
COMMENT ON COLUMN logistics.replenishment_item.reorder_point_qty IS '보충 시점(품목 기본 단위).';
COMMENT ON COLUMN logistics.replenishment_item.target_qty IS '유지량(품목 기본 단위). 보충 시점보다 커야 한다.';
COMMENT ON COLUMN logistics.replenishment_item.source_warehouse_id IS '출고 자재 창고. 같은 공장·활성·불량창고 아님은 서비스가 검사한다.';

CREATE INDEX ix_replenishment_item_item ON logistics.replenishment_item (item_id);

-- 생산 창고별 자동 보충 실행 시각.
CREATE TABLE logistics.replenishment_warehouse_setting (
    warehouse_id bigint      PRIMARY KEY REFERENCES mdm.warehouse(warehouse_id),
    run_time     varchar(5),
    updated_at   timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_by   bigint,
    version_no   int         NOT NULL DEFAULT 1,
    CONSTRAINT ck_replenishment_warehouse_setting_version CHECK (version_no > 0)
);

COMMENT ON TABLE logistics.replenishment_warehouse_setting IS '생산 창고별 자동 보충 실행 시각.';
COMMENT ON COLUMN logistics.replenishment_warehouse_setting.run_time IS
    '공장 현지 HH:MM. NULL = 공장 정책 REPLENISHMENT_RUN_TIME, 그것도 없으면 서버 기본 01:00.';

-- 실행의 품목별 결과. 보충 시점 이상인 품목은 행을 남기지 않는다.
CREATE TABLE logistics.replenishment_run_line (
    replenishment_run_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    replenishment_run_id      bigint         NOT NULL REFERENCES logistics.replenishment_run(replenishment_run_id),
    item_id                   bigint         NOT NULL REFERENCES mdm.item(item_id),
    result_code               varchar(30)    NOT NULL,
    usable_qty                decimal(20, 6) NOT NULL,
    requested_qty             decimal(20, 6) NOT NULL DEFAULT 0,
    shortage_qty              decimal(20, 6) NOT NULL DEFAULT 0,
    material_issue_request_id bigint REFERENCES logistics.material_issue_request(material_issue_request_id),
    CONSTRAINT ck_replenishment_run_line_result
        CHECK (result_code IN ('CREATED', 'SHORTAGE', 'IN_PROGRESS', 'NO_SOURCE_STOCK', 'SOURCE_INACTIVE'))
);

COMMENT ON TABLE logistics.replenishment_run_line IS '자동 보충 실행의 품목별 결과(계산 당시 값).';
COMMENT ON COLUMN logistics.replenishment_run_line.result_code IS
    'CREATED | SHORTAGE(일부만 만듦) | IN_PROGRESS(진행 중 보충 있음) | NO_SOURCE_STOCK | SOURCE_INACTIVE';
COMMENT ON COLUMN logistics.replenishment_run_line.material_issue_request_id IS '이 품목으로 만든 창고 보충 요청.';

CREATE INDEX ix_replenishment_run_line_run ON logistics.replenishment_run_line (replenishment_run_id);

