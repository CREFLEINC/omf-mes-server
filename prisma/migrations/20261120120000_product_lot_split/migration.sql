-- 피처 013 생산 LOT 수량 분리(omf-all-around#303) — 분리 기록 표·코드값. 기존 행은 바꾸지 않는다.

-- ① 분리 기록 — 분리 1회 = 1행. confirmed_at 이 NULL 이면 PDA 확인 대기다(피킹·재분리·추적 시스템 출고 거절).
CREATE TABLE trace.product_lot_split (
    -- BY DEFAULT — 분리 서비스가 번호를 먼저 받아 자식 LOT 원천(source_id)에 싣고 같은 번호로 행을 쓴다.
    product_lot_split_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id               bigint      NOT NULL REFERENCES mdm.plant(plant_id),
    parent_lot_id          bigint      NOT NULL REFERENCES trace.lot(lot_id),
    child_lot_id           bigint      NOT NULL REFERENCES trace.lot(lot_id),
    warehouse_id           bigint      NOT NULL REFERENCES mdm.warehouse(warehouse_id),
    location_id            bigint      NOT NULL REFERENCES mdm.location(location_id),
    split_qty              app.qty_t   NOT NULL CHECK (split_qty > 0),
    uom_id                 bigint      NOT NULL REFERENCES mdm.uom(uom_id),
    split_at               timestamptz NOT NULL DEFAULT clock_timestamp(),
    split_by               bigint,
    split_worker_no        varchar(50),
    split_terminal_id      bigint      REFERENCES mdm.terminal(terminal_id),
    confirmed_at           timestamptz,
    confirmed_by           bigint,
    confirmed_worker_no    varchar(50),
    confirmed_terminal_id  bigint      REFERENCES mdm.terminal(terminal_id),
    created_at             timestamptz NOT NULL DEFAULT clock_timestamp(),
    created_by             bigint,
    updated_at             timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_by             bigint,
    version_no             integer     NOT NULL DEFAULT 1 CHECK (version_no > 0),
    CONSTRAINT ck_product_lot_split_lots CHECK (parent_lot_id <> child_lot_id),
    CONSTRAINT ck_product_lot_split_confirmed CHECK (confirmed_at IS NULL OR confirmed_terminal_id IS NOT NULL)
);
COMMENT ON TABLE trace.product_lot_split IS
  '생산 LOT 수량 분리 기록(POP P-04-08) — 원래 LOT 에서 자식 LOT(원천 PRODUCT_LOT_SPLIT)을 떼어 낸 1회. 거래번호 PLS-{id}(omf-all-around#303)';
COMMENT ON COLUMN trace.product_lot_split.child_lot_id IS '자식 LOT — 분리 하나에서만 태어난다';
COMMENT ON COLUMN trace.product_lot_split.location_id IS '분리한 자리 — 자식 LOT 재고가 생긴 위치';
COMMENT ON COLUMN trace.product_lot_split.split_worker_no IS '분리한 POP 작업자 번호(X-Worker-No)';
COMMENT ON COLUMN trace.product_lot_split.confirmed_at IS 'PDA 두 라벨 확인 시각(M-04-05). NULL = 확인 대기. 한 번 채우면 되돌리지 않는다';
COMMENT ON COLUMN trace.product_lot_split.confirmed_worker_no IS '확인한 PDA 작업자 번호(X-Worker-No)';
CREATE UNIQUE INDEX uq_product_lot_split_child ON trace.product_lot_split (child_lot_id);
-- 원래 LOT 당 확인 대기는 하나다 — 확인 전 재분리 거절(LOT_SPLIT_UNCONFIRMED)의 안전망.
CREATE UNIQUE INDEX uq_product_lot_split_parent_unconfirmed
    ON trace.product_lot_split (parent_lot_id) WHERE confirmed_at IS NULL;
CREATE INDEX ix_product_lot_split_unconfirmed
    ON trace.product_lot_split (plant_id, split_at DESC) WHERE confirmed_at IS NULL;
CREATE INDEX ix_product_lot_split_parent ON trace.product_lot_split (parent_lot_id, split_at DESC);

-- ② 코드값. ⭐ 배포는 migrate deploy 만 돈다 — seed.ts 에도 같은 값이 있다.
--    REISSUE_REASON.LOT_SPLIT 은 서버(분리)만 쓰는 사유다. 고객이 꺼도 분리는 된다.
INSERT INTO mdm.code_value (code_group_id, code, code_name, display_order, name_ko, name_vi)
SELECT cg.code_group_id, v.code, v.code_name, v.display_order, v.code_name, v.name_vi
  FROM mdm.code_group cg
  JOIN (VALUES
    ('REISSUE_REASON', 'LOT_SPLIT', 'LOT 분리', 60, 'Tách LOT'),
    ('LOT_SOURCE_TYPE', 'PRODUCT_LOT_SPLIT', '생산 LOT 분리', 70, 'Tách LOT sản xuất')
  ) AS v(group_code, code, code_name, display_order, name_vi) ON cg.group_code = v.group_code
ON CONFLICT (code_group_id, code) DO NOTHING;
