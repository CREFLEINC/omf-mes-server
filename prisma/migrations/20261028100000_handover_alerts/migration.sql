-- 인계 작업 알림 — 알림센터·Zalo + 단말 대기 작업 수 (omf-all-around#190 · specs/002-terminal-task-alerts data-model §1·§2).
-- forward-only: 표·칸 추가만 한다. 기존 알림 표의 다른 칸·CHECK·인덱스는 건드리지 않는다.

-- §1 공장 × 인계 작업 종류 설정 ---------------------------------------------------

CREATE TABLE app.handover_alert_setting (
  handover_alert_setting_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plant_id        bigint      NOT NULL REFERENCES mdm.plant(plant_id),
  alert_type_code varchar(60) NOT NULL,
  is_enabled      boolean     NOT NULL DEFAULT false,
  zalo_enabled    boolean     NOT NULL DEFAULT false,
  version_no      integer     NOT NULL DEFAULT 1 CHECK (version_no > 0),
  created_at      timestamptz NOT NULL DEFAULT clock_timestamp(),
  created_by      bigint,
  updated_at      timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_by      bigint,
  CONSTRAINT ck_handover_alert_setting_zalo CHECK (NOT zalo_enabled OR is_enabled),
  CONSTRAINT uq_handover_alert_setting UNIQUE (plant_id, alert_type_code)
);

CREATE TABLE app.handover_alert_recipient (
  handover_alert_setting_id bigint NOT NULL REFERENCES app.handover_alert_setting(handover_alert_setting_id),
  app_user_id               bigint NOT NULL REFERENCES app.app_user(app_user_id),
  created_at                timestamptz NOT NULL DEFAULT clock_timestamp(),
  created_by                bigint,
  CONSTRAINT pk_handover_alert_recipient PRIMARY KEY (handover_alert_setting_id, app_user_id)
);
CREATE INDEX ix_handover_alert_recipient_user ON app.handover_alert_recipient (app_user_id);

COMMENT ON TABLE app.handover_alert_setting IS
  '공장×인계 작업 종류 알림 설정. 행이 없으면 끔·Zalo 끔·담당자 0명·version 1 로 읽는다(GET 은 행을 만들지 않는다).';
COMMENT ON COLUMN app.handover_alert_setting.alert_type_code IS '인계 작업 종류 10종 중 하나(서버 HANDOVER_ALERT_TYPES 검증).';
COMMENT ON COLUMN app.handover_alert_setting.is_enabled IS '알림 실행 여부. 처음엔 꺼짐.';
COMMENT ON COLUMN app.handover_alert_setting.zalo_enabled IS 'Zalo 부가 전달. is_enabled=true 일 때만 true 가 될 수 있다.';
COMMENT ON TABLE app.handover_alert_recipient IS '인계 작업 알림 담당자. 설정 하나에 최대 5명(서버 검사).';

-- §2 단말 창고 ------------------------------------------------------------------

ALTER TABLE mdm.terminal
  ADD COLUMN warehouse_id bigint REFERENCES mdm.warehouse(warehouse_id);
CREATE INDEX ix_terminal_warehouse ON mdm.terminal (warehouse_id);

COMMENT ON COLUMN mdm.terminal.warehouse_id IS
  '단말의 창고(POP·모바일). 같은 공장 창고만. 비우면 공장 전체 작업을 본다.';

-- §2 Zalo 발송 우선순위 -----------------------------------------------------------

ALTER TABLE app.zalo_delivery
  ADD COLUMN priority smallint NOT NULL DEFAULT 0;
-- 기존 ix_zalo_delivery_due 는 남긴다 — 배포 중 옛 코드의 정렬이 그 인덱스를 쓴다.
CREATE INDEX ix_zalo_delivery_due_priority ON app.zalo_delivery (status_code, priority, next_attempt_at);

COMMENT ON COLUMN app.zalo_delivery.priority IS
  '발송 순서(작을수록 먼저). 기존 이벤트 알림 0, 인계 작업 알림 1.';
