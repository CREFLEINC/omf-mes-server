-- ERP 보내기 — MES 가 중계 DB 의 받는 표(T_IF_RCV_*)에 넣은 행 하나가 한 줄이다. 연계 메시지 하나(W/O 마감 같은 묶음)가
-- 여러 표의 여러 행이 된다.
-- 키(건 번호·IF_SEQ)를 중계 DB 에 넣기 «전에» 여기 적는다. 넣다 끊겨 다시 넣어도 같은 키라 중계 표의 PK 가 두 번째를 막는다.
-- row_values 는 넣은 칸과 값 그대로다 — 취소(CREATE_TYPE C) 행은 이것을 복사해 만든다.
CREATE TABLE integration.erp_outbound_row (
  erp_outbound_row_id    bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  integration_message_id bigint       NOT NULL REFERENCES integration.integration_message(integration_message_id),
  relay_table_name       varchar(50)  NOT NULL,
  -- IF_SEQ 를 세는 단위(건). 생산입고는 공장|ERP W/O 번호다.
  document_no            varchar(50)  NOT NULL,
  -- 중계 표 PK 값을 PK 순서대로 '|' 로 이은 것.
  relay_key              varchar(200) NOT NULL,
  if_seq                 integer,
  create_type_code       char(1)      NOT NULL,
  cancels_row_id         bigint       REFERENCES integration.erp_outbound_row(erp_outbound_row_id),
  row_values             jsonb        NOT NULL,
  status_code            varchar(20)  NOT NULL,
  -- 중계 표의 MES_INF_ID(IDENTITY). ERP 회신을 이것으로 읽는다.
  relay_inf_id           bigint,
  erp_document_no        varchar(30),
  erp_error_message      text,
  inserted_at            timestamptz,
  erp_applied_at         timestamptz,
  created_at             timestamptz  NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT uq_erp_outbound_row_key UNIQUE (relay_table_name, relay_key),
  CONSTRAINT ck_erp_outbound_row_create_type CHECK (create_type_code IN ('A', 'C')),
  CONSTRAINT ck_erp_outbound_row_cancels CHECK ((create_type_code = 'C') = (cancels_row_id IS NOT NULL)),
  CONSTRAINT ck_erp_outbound_row_status CHECK (status_code IN ('RESERVED', 'INSERTED', 'APPLIED', 'REJECTED'))
);

CREATE INDEX ix_erp_outbound_row_message ON integration.erp_outbound_row (integration_message_id);
CREATE INDEX ix_erp_outbound_row_document ON integration.erp_outbound_row (relay_table_name, document_no);
-- ERP 회신을 기다리는 행만 — 반영된 행이 쌓여도 회신 읽기가 훑는 양은 그대로다.
CREATE INDEX ix_erp_outbound_row_waiting ON integration.erp_outbound_row (relay_table_name)
  WHERE status_code = 'INSERTED';
