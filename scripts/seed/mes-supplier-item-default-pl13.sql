   WHERE (d.lot_qty, d.package_uom_id, d.package_count, d.qty_per_package)
         IS DISTINCT FROM (EXCLUDED.lot_qty, EXCLUDED.package_uom_id, EXCLUDED.package_count, EXCLUDED.qty_per_package)
  RETURNING (xmax = 0) AS inserted
)
