WITH ok AS (
  SELECT * FROM resolved WHERE item_id IS NOT NULL AND supplier_id IS NOT NULL AND item_active AND supplier_active
), up AS (
  INSERT INTO mdm.supplier_item_default AS d (plant_id, supplier_id, item_id, lot_qty, package_uom_id, package_count, qty_per_package)
